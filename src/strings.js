  visit: { one: 'زيارة واحدة', two: 'زيارتان', few: 'زيارات', many: 'زيارة' },
  service: { one: 'خدمة واحدة', two: 'خدمتان', few: 'خدمات', many: 'خدمة' },
  person: { one: 'شخص واحد', two: 'شخصان', few: 'أشخاص', many: 'شخصاً' },
