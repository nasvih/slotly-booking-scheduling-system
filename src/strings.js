/** `c(3, 'booking')` → "3 مواعيد" · `c(1, 'booking')` → "موعد واحد" */
export function c(n, key) {
  const f = NOUN[key];
  const x = Number(n) || 0;
  if (!f) return String(n);
  if (x === 0) return `0 ${f.few}`;
  if (x === 1) return f.one;
  if (x === 2) return f.two;
  const m = x % 100;
  if (m >= 3 && m <= 10) return `${x} ${f.few}`;
  return `${x} ${f.many}`;
}

/* English plural, kept as a helper so the two halves read the same way. */
const s = (n, word, plural) => `${n} ${Number(n) === 1 ? word : (plural || `${word}s`)}`;

